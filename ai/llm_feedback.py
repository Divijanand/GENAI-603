import json
import os
from collections import Counter

from dotenv import load_dotenv
from google import genai

load_dotenv()

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])


def generate_feedback(user_code, analysis_results):
    """
    Generates beginner-friendly Python feedback using Gemini.

    Args:
        user_code (str): Python code submitted by the student.
        analysis_results (dict): Findings returned by AST and Ruff.

    Returns:
        dict: Structured feedback containing explanations and hints
        for the detected Python issues.
    """

    prompt = f"""
    You are CodeMentor AI, a patient Python programming tutor for beginner students.

    Analyze the following Python code and its static analysis findings.

    Student's Python code:
    ```python
    {user_code}
    ```

    Verified static analysis findings:
    {analysis_results}

    For each finding:
    1. Explain the problem in simple, beginner-friendly language.
    2. Explain why it happens.
    3. Give a helpful hint for fixing it without immediately
       providing the complete corrected code.

    Explain ONLY the issues listed in the static analysis findings.
    Do not add new issues or change their rule codes.

    For each issue, provide:
    - rule: the exact rule code from the findings
    - explanation: a beginner-friendly explanation of the issue found
    - hint: guidance without giving the full solution

    Return valid JSON with this structure:
    {{
        "feedback": [
            {{
                "rule": "F821",
                "explanation": "Explanation here",
                "hint": "Hint here"
            }}
        ]
    }}

    Do not include Markdown formatting or additional text.
    """

    response = client.models.generate_content(
        model="gemini-3.5-flash",
        contents=prompt,
        config={"response_mime_type": "application/json"},
    )

    llm_feedback = json.loads(response.text)
    if validate_feedback(analysis_results, llm_feedback):
        return llm_feedback
    else:
        raise ValueError("Gemini returned invalid feedback")


def validate_feedback(analysis_results, feedback):
    """
    Validates Gemini's feedback against AST/Ruff findings.

    Args:
        analysis_results (dict): Verified static analysis findings.
        feedback (dict): Structured feedback generated by Gemini.

    Returns:
        bool: True if the feedback matches the findings,
        otherwise False.
    """

    if not isinstance(feedback, dict):
        return False

    if not isinstance(feedback.get("feedback"), list):
        return False

    for row in feedback["feedback"]:
        if not isinstance(row, dict):
            return False

    expected_rules = []
    for issue in analysis_results["issues"]:
        expected_rules.append(issue["type"])

    llm_output_rules = []
    for item in feedback["feedback"]:
        rule = item.get("rule")
        explanation = item.get("explanation")
        hint = item.get("hint")

        if not all(isinstance(val, str) for val in (explanation, hint, rule)):
            return False

        if not (explanation.strip() and hint.strip() and rule.strip()):
            return False

        llm_output_rules.append(rule)

    return Counter(expected_rules) == Counter(llm_output_rules)
